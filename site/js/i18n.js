const pickLang = () => {
  if (I18N[settings.lang]) return settings.lang;
  for (const l of navigator.languages || [navigator.language || 'en']) {
    if (I18N[l]) return l;
    const base = l.split('-')[0];
    const hit = LANGS.find(x => x.id.split('-')[0] === base);
    if (hit) return hit.id;
  }
  return 'en';
};

let lang = pickLang();

function t(key, vars) {
  const s = I18N[lang][key] ?? I18N.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : s;
}

const ruleName = id => t(`rule.${id}.name`);
const ruleDesc = id => t(`rule.${id}.desc`);

function applyI18n() {
  document.documentElement.lang = lang;
  document.title = APP_NAME;
  $('meta[name="description"]')?.setAttribute('content', t('app.description'));
  for (const node of $$('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of $$('[data-i18n-title]')) {
    node.title = t(node.dataset.i18nTitle);
    node.setAttribute('aria-label', node.title);
  }
}

function setLang(id) {
  if (!I18N[id]) return;
  lang = id;
  settings.lang = id;
  saveSettings();
  applyI18n();
}
